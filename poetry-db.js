/**
 * 数据库工具函数
 */
const DB = {
  /**
   * 获取所有诗句（扁平化）
   * @returns {Array<{line: string, poem: object}>}
   */
  getAllLines() {
    const result = [];
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        result.push({ line, poem });
      }
    }
    return result;
  },

  /**
   * 获取包含指定字符的所有诗句
   */
  getLinesByChar(char) {
    return this.getAllLines().filter(item => item.line.includes(char));
  },

  /**
   * 获取以指定字符开头的所有诗句
   */
  getLinesByFirstChar(char) {
    return this.getAllLines().filter(item => item.line[0] === char);
  },

  /**
   * 获取以指定字符结尾的所有诗句
   */
  getLinesByLastChar(char) {
    return this.getAllLines().filter(item => {
      const last = item.line[item.line.length - 1];
      return last === char;
    });
  },

  /**
   * 验证诗句是否存在于数据库
   */
  validateLine(input) {
    const normalized = input.trim().replace(/[，。、？！；：""''（）\s]/g, '');
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        if (line === normalized) return { valid: true, poem, line };
      }
    }
    return { valid: false };
  },

  /**
   * 根据诗句获取完整诗信息
   */
  getPoemByLine(line) {
    for (const poem of POETRY_DB) {
      if (poem.lines.includes(line)) return poem;
    }
    return null;
  },

  /**
   * 获取所有可用作飞花令关键字的字符（出现次数 >= 3）
   */
  getFlyFlowerChars() {
    const charMap = {};
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        for (const char of line) {
          charMap[char] = (charMap[char] || 0) + 1;
        }
      }
    }
    return Object.keys(charMap)
      .filter(char => charMap[char] >= 3)
      .sort((a, b) => charMap[b] - charMap[a]);
  },

  /**
   * 获取所有首字（用于接龙策略分析）
   */
  getStartChars() {
    const chars = new Set();
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        chars.add(line[0]);
      }
    }
    return chars;
  },

  /**
   * 获取所有末字（用于接龙策略分析）
   */
  getEndChars() {
    const chars = new Set();
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        chars.add(line[line.length - 1]);
      }
    }
    return chars;
  },

  /**
   * 获取末字频率表（用于 AI 策略：优先选末字罕见的句）
   */
  getEndCharFrequency() {
    const freq = {};
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        const last = line[line.length - 1];
        freq[last] = (freq[last] || 0) + 1;
      }
    }
    return freq;
  },

  /**
   * 获取首字频率表（用于判断某字作为首字的难度）
   */
  getStartCharFrequency() {
    const freq = {};
    for (const poem of POETRY_DB) {
      for (const line of poem.lines) {
        const first = line[0];
        freq[first] = (freq[first] || 0) + 1;
      }
    }
    return freq;
  },

  /**
   * 获取统计数据
   */
  getStats() {
    let lineCount = 0;
    for (const poem of POETRY_DB) {
      lineCount += poem.lines.length;
    }
    return {
      poems: POETRY_DB.length,
      lines: lineCount,
      flyChars: this.getFlyFlowerChars().length
    };
  }
};
