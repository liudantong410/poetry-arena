/**
 * 成语工具（供 AI 使用）
 */
const IdiomDB = {
  _byFirst: null,

  init() {
    this._byFirst = {};
    this._isSet = new Set(IDIOMS);
    this._all = [...IDIOMS];
    IDIOMS.forEach(idiom => {
      const fc = idiom[0];
      if (!this._byFirst[fc]) this._byFirst[fc] = [];
      this._byFirst[fc].push(idiom);
    });
  },

  ensureInit() {
    if (!this._byFirst) this.init();
  },

  /** 玩家输入是否在成语库中 */
  has(idiom) {
    this.ensureInit();
    return this._isSet.has(idiom);
  },

  /** 成语总数 */
  getSize() {
    this.ensureInit();
    return this._all.length;
  },

  /** 获取以指定字开头且未用过的成语 */
  getAvailableForChar(char, usedSet) {
    this.ensureInit();
    const list = this._byFirst[char] || [];
    return list.filter(idiom => !usedSet.has(idiom));
  },

  /** 指定字开头还有多少未用成语 */
  continuationCount(char, usedSet) {
    return this.getAvailableForChar(char, usedSet).length;
  },

  /**
   * AI 选词
   * @param {string} difficulty 'easy'|'medium'|'hard'
   * @param {string} requiredChar 必须以该字开头
   * @param {Set} usedSet 已用成语
   * @returns {idiom, lastChar} | null
   */
  pickAI(difficulty, requiredChar, usedSet) {
    this.ensureInit();
    const available = this.getAvailableForChar(requiredChar, usedSet);
    if (available.length === 0) return null;

    // 为每个候选计算末字的后续接续数
    const scored = available.map(idiom => {
      const lastChar = idiom[idiom.length - 1];
      const cont = this.continuationCount(lastChar, usedSet);
      return { idiom, lastChar, cont };
    });

    if (difficulty === 'easy') {
      // 简单：优先末字接续多的（让玩家容易接）
      scored.sort((a, b) => b.cont - a.cont);
      const pool = scored.slice(0, Math.min(scored.length, 5));
      return pool[Math.floor(Math.random() * pool.length)];
    } else if (difficulty === 'hard') {
      // 困难：优先末字接续少的（堵死玩家）
      scored.sort((a, b) => a.cont - b.cont);
      const pool = scored.slice(0, Math.min(scored.length, 3));
      return pool[Math.floor(Math.random() * pool.length)];
    } else {
      // 中等：随机
      return scored[Math.floor(Math.random() * scored.length)];
    }
  }
};
